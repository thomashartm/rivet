#!/usr/bin/env bash
# Starts the playground databases (PostgreSQL and MySQL). Writes .env in the
# repository root on the first run, with random passwords, and adds missing
# keys to an existing .env. Existing values are kept, so the passwords match
# the data volumes. `rivet` reads its connections from .env:
#   RIVET_DATABASE_URL        default (PostgreSQL)   -> rivet
#   RIVET_DATABASE_URL_PG     PostgreSQL             -> rivet pg
#   RIVET_DATABASE_URL_MYSQL  MySQL                  -> rivet mysql
# The servers use TLS with a throwaway certificate for `localhost`
# (docker/test-certs.sh), so the addresses use `localhost` and trust only its
# CA: ?tls_ca=docker/test-certs/ca.pem.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
env_file="$root/.env"
ca="$root/docker/test-certs/ca.pem"

if [[ ! -f "$env_file" ]]; then
    (umask 077 && echo "# Generated by docker/playground.sh. Local playground only; never commit." > "$env_file")
    echo "wrote $env_file"
fi

# The value of a key in .env, or empty.
get() { grep -m1 "^$1=" "$env_file" | cut -d= -f2- || true; }
# Appends KEY=value if .env has no such key.
add() { [[ -n "$(get "$1")" ]] || echo "$1=$2" >> "$env_file"; }
password() { local value; value="$(get "$1")"; echo "${value:-$(openssl rand -hex 16)}"; }

pg_password="$(password POSTGRES_PASSWORD)"
pg_url="postgres://rivet:$pg_password@localhost:55432/playground?tls_ca=$ca"
add POSTGRES_USER rivet
add POSTGRES_PASSWORD "$pg_password"
add POSTGRES_DB playground
add RIVET_DATABASE_URL "$pg_url"
add RIVET_DATABASE_URL_PG "$pg_url"

mysql_password="$(password MYSQL_PASSWORD)"
add MYSQL_USER rivet
add MYSQL_PASSWORD "$mysql_password"
add MYSQL_ROOT_PASSWORD "$(password MYSQL_ROOT_PASSWORD)"
add MYSQL_DATABASE playground
add RIVET_DATABASE_URL_MYSQL "mysql://rivet:$mysql_password@localhost:53306/playground?tls_ca=$ca"

# A .env from before playground TLS: the default playground addresses
# (127.0.0.1, ?tls=off or no tls parameter) move to localhost with the CA.
# Other lines, also each password, stay as they are.
updated="$(mktemp "$env_file.XXXXXX")"
awk -v ca="$ca" '/^RIVET_DATABASE_URL[A-Z0-9_]*=[a-z]+:\/\/[^@]*@127\.0\.0\.1:(55432|53306)\/playground(\?tls=off)?$/ {
        sub(/@127\.0\.0\.1:/, "@localhost:"); sub(/\?tls=off$/, ""); $0 = $0 "?tls_ca=" ca; changed++
    }
    { print }
    END { if (changed) printf "moved %d playground address(es) in .env to TLS\n", changed > "/dev/stderr" }' \
    "$env_file" > "$updated"
mv "$updated" "$env_file"

docker compose --env-file "$env_file" -f "$root/docker/compose.playground.yml" up -d --wait
echo "playground ready. Run: make run (PostgreSQL) or make run-mysql"
