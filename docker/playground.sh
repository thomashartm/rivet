#!/usr/bin/env bash
# Starts the playground PostgreSQL. On the first run it writes .env in the
# repository root with a random password; `rivet` reads RIVET_DATABASE_URL
# from it. An existing .env is kept, so the password matches the data volume.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
env_file="$root/.env"

if [[ ! -f "$env_file" ]]; then
    password="$(openssl rand -hex 16)"
    (
        umask 077
        {
            echo "# Generated by docker/playground.sh. Local playground only; never commit."
            echo "POSTGRES_USER=rivet"
            echo "POSTGRES_PASSWORD=$password"
            echo "POSTGRES_DB=playground"
            echo "RIVET_DATABASE_URL=postgres://rivet:$password@127.0.0.1:55432/playground"
        } > "$env_file"
    )
    echo "wrote $env_file"
fi

docker compose --env-file "$env_file" -f "$root/docker/compose.playground.yml" up -d --wait
echo "playground ready. Run: cargo run -p rivet-cli"
